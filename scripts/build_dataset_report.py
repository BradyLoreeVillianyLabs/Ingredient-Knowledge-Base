#!/usr/bin/env python3
"""Build a Markdown dataset report for maintainers and app release review."""

from __future__ import annotations

import csv
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
OUT_PATH = ROOT / "docs" / "DATASET_REPORT.md"


def read_csv(path: Path) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def count_ingredient_rows() -> tuple[int, Counter[str], Counter[str]]:
    total = 0
    by_category: Counter[str] = Counter()
    by_status: Counter[str] = Counter()
    for path in sorted(DATA_DIR.rglob("*.csv")):
        if "metadata" in path.parts or "generated" in path.parts:
            continue
        for row in read_csv(path):
            if row.get("ingredient_id"):
                total += 1
                by_category[row.get("category", "unknown") or "unknown"] += 1
                by_status[row.get("review_status", "unknown") or "unknown"] += 1
    return total, by_category, by_status


def metadata_counts() -> dict[str, int]:
    files = {
        "facts": DATA_DIR / "metadata" / "16_ingredient_facts.csv",
        "regulatory_status": DATA_DIR / "metadata" / "15_regulatory_status.csv",
        "historical_use": DATA_DIR / "metadata" / "17_historical_use.csv",
        "ocr_aliases": DATA_DIR / "metadata" / "14_ocr_aliases.csv",
        "common_combinations": DATA_DIR / "metadata" / "18_common_combinations.csv",
        "sources": DATA_DIR / "metadata" / "source_registry.csv",
        "citations": DATA_DIR / "metadata" / "citation_registry.csv",
        "review_queue": DATA_DIR / "metadata" / "review_queue.csv",
    }
    return {name: len(read_csv(path)) for name, path in files.items()}


def format_counter(counter: Counter[str]) -> str:
    if not counter:
        return "_None_\n"
    lines = ["| Value | Count |", "|---|---:|"]
    for value, count in counter.most_common():
        lines.append(f"| {value} | {count} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    total, by_category, by_status = count_ingredient_rows()
    meta = metadata_counts()

    report = [
        "# Dataset Report",
        "",
        "Generated by `scripts/build_dataset_report.py`.",
        "",
        "## Curated ingredient rows",
        "",
        f"Total curated ingredient rows: **{total}**",
        "",
        "### By category",
        "",
        format_counter(by_category),
        "### By review status",
        "",
        format_counter(by_status),
        "## Metadata tables",
        "",
        "| Table | Rows |",
        "|---|---:|",
    ]
    for name, count in meta.items():
        report.append(f"| {name} | {count} |")

    report.extend(
        [
            "",
            "## Release interpretation",
            "",
            "- `draft` rows are useful for internal/app educational previews.",
            "- `needs_source` rows need citation review before public factual or regulatory display.",
            "- `generated` and `mined` rows should be treated as machine outputs until curated.",
            "",
        ]
    )
    OUT_PATH.write_text("\n".join(report), encoding="utf-8")
    print(f"Wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
